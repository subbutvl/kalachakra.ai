// Generates the Lichun (solar new year, sun at 315° apparent ecliptic longitude)
// table used by the Kua cutoff (rules spec 3.8, decision D12).
//
// Method: Meeus, "Astronomical Algorithms", ch. 25 (low-accuracy solar
// coordinates, about 0.01°), with a ΔT approximation for TT − UT. The
// resulting instants are good to roughly ±20 minutes, which only matters for
// births on the Lichun day itself; the engine flags those.
//
// Run: node packages/rules/scripts/gen-lichun.mjs
// Writes the "lichun" block of packages/rules/v1.0/kua.json in place.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const FIRST_YEAR = 1900;
const LAST_YEAR = 2100;
const TARGET = 315;

const rad = (d) => (d * Math.PI) / 180;
const norm = (d) => ((d % 360) + 360) % 360;

function julianDayUTC(ms) {
  return ms / 86400000 + 2440587.5;
}

// Espenak–Meeus polynomial approximation of ΔT in seconds.
function deltaT(year) {
  if (year < 1920) {
    const t = year - 1900;
    return -2.79 + 1.494119 * t - 0.0598939 * t ** 2 + 0.0061966 * t ** 3 - 0.000197 * t ** 4;
  }
  if (year < 1941) {
    const t = year - 1920;
    return 21.2 + 0.84493 * t - 0.0761 * t ** 2 + 0.0020936 * t ** 3;
  }
  if (year < 1961) {
    const t = year - 1950;
    return 29.07 + 0.407 * t - t ** 2 / 233 + t ** 3 / 2547;
  }
  if (year < 1986) {
    const t = year - 1975;
    return 45.45 + 1.067 * t - t ** 2 / 260 - t ** 3 / 718;
  }
  if (year < 2005) {
    const t = year - 2000;
    return (
      63.86 +
      0.3345 * t -
      0.060374 * t ** 2 +
      0.0017275 * t ** 3 +
      0.000651814 * t ** 4 +
      0.00002373599 * t ** 5
    );
  }
  if (year < 2050) {
    const t = year - 2000;
    return 62.92 + 0.32217 * t + 0.005589 * t ** 2;
  }
  const u = (year - 1820) / 100;
  return -20 + 32 * u ** 2 - 0.5628 * (2150 - year);
}

function apparentSolarLongitude(ms, year) {
  const jde = julianDayUTC(ms) + deltaT(year) / 86400;
  const T = (jde - 2451545.0) / 36525;
  const L0 = 280.46646 + 36000.76983 * T + 0.0003032 * T * T;
  const M = 357.52911 + 35999.05029 * T - 0.0001537 * T * T;
  const C =
    (1.914602 - 0.004817 * T - 0.000014 * T * T) * Math.sin(rad(M)) +
    (0.019993 - 0.000101 * T) * Math.sin(rad(2 * M)) +
    0.000289 * Math.sin(rad(3 * M));
  const omega = 125.04 - 1934.136 * T;
  return norm(L0 + C - 0.00569 - 0.00478 * Math.sin(rad(omega)));
}

function lichun(year) {
  let lo = Date.UTC(year, 1, 1);
  let hi = Date.UTC(year, 1, 7);
  for (let i = 0; i < 60; i++) {
    const mid = (lo + hi) / 2;
    if (apparentSolarLongitude(mid, year) < TARGET) lo = mid;
    else hi = mid;
  }
  const minute = 60000;
  return new Date(Math.round(hi / minute) * minute).toISOString().replace(":00.000Z", "Z");
}

const here = dirname(fileURLToPath(import.meta.url));
const kuaPath = join(here, "..", "v1.0", "kua.json");
const source = readFileSync(kuaPath, "utf8");
const lines = [];
for (let y = FIRST_YEAR; y <= LAST_YEAR; y++) lines.push(`      "${y}": "${lichun(y)}"`);
const block = `"lichun": {
    "$comment": "Generated by packages/rules/scripts/gen-lichun.mjs. UTC instant the sun reaches 315 degrees apparent longitude (Meeus ch. 25, about 20 minutes). Do not edit by hand.",
    "first_year": ${FIRST_YEAR},
    "last_year": ${LAST_YEAR},
    "precision_minutes": 20,
    "utc": {
${lines.join(",\n")}
    }
  }`;
// Replace the existing "lichun" block (always the last key) and keep the hand layout above it.
const start = source.indexOf('"lichun":');
if (start < 0) throw new Error('kua.json has no "lichun" key');
const end = source.lastIndexOf("}");
const updated = source.slice(0, start) + block + "\n" + source.slice(end);
JSON.parse(updated); // sanity check
writeFileSync(kuaPath, updated);
console.log(`Wrote ${LAST_YEAR - FIRST_YEAR + 1} Lichun instants to ${kuaPath}`);
